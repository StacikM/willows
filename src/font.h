#pragma once
/* Fonts. Two kinds share one struct:
   - anti-aliased glyph bitmaps generated by tools/host/mkfont.c (src/fontdata.c: Open Sans + Hack), or
   - the built-in 8x16 bitmap font, scaled (scale > 0) - used until fontdata.c has been generated. */
struct fglyph { unsigned short cp; unsigned char w, h; signed char xoff, yoff; unsigned short adv16; unsigned int off; };   /* adv16: advance in 1/16 px */
struct font { const char *name; int px, ascent, lineh, nglyph; const struct fglyph *g; const unsigned char *bits; int scale, bold; };
enum { FS_REGULAR, FS_BOLD, FS_ITALIC, FS_MONO, FS_MONOBOLD };
const struct font *font_find(int style, int px);          /* nearest available size */
