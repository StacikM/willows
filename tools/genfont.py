#!/usr/bin/env python3
"""genfont.py -> src/font.c: first 128 glyphs of an 8x16 PSF console font (from the kbd package)."""
import gzip, struct, sys
data = gzip.open(sys.argv[1]).read()
if data[:4] == b"\x72\xb5\x4a\x86":
    hs, flags, n, cs, h, w = struct.unpack_from("<6I", data, 8)
else:
    assert data[:2] == b"\x36\x04"; hs, n, cs = 4, 256, data[3]; h = cs; w = 8
assert (w, h) == (8, 16)
rows = [data[hs + i*cs: hs + i*cs + 16] for i in range(128)]
with open(sys.argv[2], "w") as f:
    f.write("/* generated by tools/genfont.py */\nconst unsigned char font8x16[128][16] = {\n")
    for r in rows: f.write("{" + ",".join("0x%02x" % b for b in r) + "},\n")
    f.write("};\n")
