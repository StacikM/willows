/* mkfont: rasterise TTF fonts into anti-aliased glyph bitmaps -> src/fontdata.c.
   Host-side build tool (uses floating point; the kernel does not). Needs stb_truetype.h (public domain, next to this file).
   build + run from the repo root:
       gcc -O2 -o /tmp/mkfont tools/host/mkfont.c -Itools/host -lm && /tmp/mkfont > src/fontdata.c
   Fonts: Open Sans (Apache 2.0) and Hack (MIT) from /usr/share/fonts - edit `specs` to use others. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

struct spec { const char *name, *file; int style; int sizes[12]; };
static const struct spec specs[] = {
  { "sans",  "/usr/share/fonts/OpenSans/OpenSans-Regular.ttf", 0, {11,12,13,14,15,16,18,20,24,28,32,0} },
  { "sansb", "/usr/share/fonts/OpenSans/OpenSans-Bold.ttf",    1, {11,12,13,14,15,16,18,20,24,28,32,0} },
  { "sansi", "/usr/share/fonts/OpenSans/OpenSans-Italic.ttf",  2, {12,13,14,15,16,18,0} },
  { "mono",  "/usr/share/fonts/TTF/Hack-Regular.ttf",          3, {12,13,14,15,16,0} },
  { "monob", "/usr/share/fonts/TTF/Hack-Bold.ttf",             4, {13,15,0} },
};
static unsigned short cps[400]; static int ncp;
static void addr(int a, int b){ for(int c=a;c<=b;c++) cps[ncp++]=c; }

int main(void){
  addr(32,126); addr(160,255);
  static const unsigned short extra[]={0x2013,0x2014,0x2018,0x2019,0x201C,0x201D,0x2022,0x2026,0x20AC,0x2122,0x2190,0x2192,0x00D7};
  for(unsigned i=0;i<sizeof extra/sizeof *extra;i++) cps[ncp++]=extra[i];
  for(int i=0;i<ncp;i++) for(int j=i+1;j<ncp;j++) if(cps[j]<cps[i]){ unsigned short t=cps[i]; cps[i]=cps[j]; cps[j]=t; }   /* sorted: binary search */
  printf("/* generated by tools/host/mkfont.c - do not edit */\n#include \"font.h\"\n");
  static char listing[16384]; listing[0]=0; int nfonts=0;
  for(unsigned si=0; si<sizeof specs/sizeof *specs; si++){
    const struct spec *sp=&specs[si];
    FILE *f=fopen(sp->file,"rb"); if(!f){ fprintf(stderr,"cannot open %s\n",sp->file); return 1; }
    fseek(f,0,SEEK_END); long n=ftell(f); fseek(f,0,SEEK_SET); unsigned char *buf=malloc(n); if(fread(buf,1,n,f)!=(size_t)n) return 1; fclose(f);
    stbtt_fontinfo info; if(!stbtt_InitFont(&info,buf,stbtt_GetFontOffsetForIndex(buf,0))){ fprintf(stderr,"bad font %s\n",sp->file); return 1; }
    for(int k=0; sp->sizes[k]; k++){
      int px=sp->sizes[k]; float scale=stbtt_ScaleForMappingEmToPixels(&info,(float)px);
      int asc,desc,gap; stbtt_GetFontVMetrics(&info,&asc,&desc,&gap);
      int ascent=(int)lroundf(asc*scale), lineh=(int)lroundf((asc-desc+gap)*scale);
      char id[48]; snprintf(id,sizeof id,"%s%d",sp->name,px);
      printf("static const unsigned char %s_bits[] = {\n",id);
      unsigned off=0; static struct { unsigned short cp; int w,h,xo,yo; unsigned adv16; unsigned off; } meta[400]; int nm=0;
      for(int c=0;c<ncp;c++){
        int cp=cps[c]; if(!stbtt_FindGlyphIndex(&info,cp)) continue;
        int w,h,xo,yo; unsigned char *bm=stbtt_GetCodepointBitmap(&info,scale,scale,cp,&w,&h,&xo,&yo);
        int adv,lsb; stbtt_GetCodepointHMetrics(&info,cp,&adv,&lsb);
        meta[nm].cp=cp; meta[nm].w=w; meta[nm].h=h; meta[nm].xo=xo; meta[nm].yo=yo; meta[nm].adv16=(unsigned)lroundf(adv*scale*16.0f); meta[nm].off=off; nm++;
        for(int i=0;i<w*h;i++){ float a=powf(bm[i]/255.0f,0.82f); printf("%d,",(int)lroundf(a*255.0f)); if(i%48==47) printf("\n"); }   /* slight gamma: crisper text */
        printf("\n"); off+=w*h; if(bm) stbtt_FreeBitmap(bm,NULL);
      }
      if(off==0) printf("0,");
      printf("};\nstatic const struct fglyph %s_g[] = {\n",id);
      for(int i=0;i<nm;i++) printf("{%u,%d,%d,%d,%d,%u,%u},\n",meta[i].cp,meta[i].w,meta[i].h,meta[i].xo,meta[i].yo,meta[i].adv16,meta[i].off);
      printf("};\n");
      char ent[200]; snprintf(ent,sizeof ent,"  {\"%s\",%d,%d,%d,%d,%s_g,%s_bits,0,0},\n",id,px,ascent,lineh,nm,id,id);
      strcat(listing,ent); nfonts++;
    }
    free(buf);
  }
  printf("const struct font all_fonts[] = {\n%s};\nconst int all_fonts_n = %d;\nconst unsigned char all_fonts_style[] = {",listing,nfonts);
  for(unsigned si=0; si<sizeof specs/sizeof *specs; si++) for(int k=0;specs[si].sizes[k];k++) printf("%d,",specs[si].style);
  printf("};\n");
  return 0;
}
